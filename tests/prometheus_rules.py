#!/usr/bin/env python3
"""Generate Prometheus recording rules from complete canonical offboarding evidence."""

from __future__ import annotations

import argparse
import csv
import os
from collections import defaultdict
from decimal import Decimal
from pathlib import Path

from tests.evidence import (
    EXPECTED_LIFETIMES,
    EXPECTED_MODES,
    EXPECTED_STRATEGIES,
    validate_offboarding,
)
from tests.lab import REPO_ROOT, staging_path

METRIC_NAME = "iam_offboarding_observed_delay_seconds"
ELEMENT = "api_authenticated"


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def render_rules(evidence: list[dict[str, str]]) -> str:
    grouped: dict[tuple[str, str, int], list[Decimal]] = defaultdict(list)
    for row in evidence:
        if row["element"] != ELEMENT or row["outcome"] != "observed":
            continue
        strategy = row["offboarding_mode"]
        mode = row["validation_mode"]
        lifetime = int(row["lifetime_s"])
        if (
            strategy not in EXPECTED_STRATEGIES
            or mode not in EXPECTED_MODES
            or lifetime not in EXPECTED_LIFETIMES
        ):
            raise ValueError("offboarding evidence contains an unsupported metric label")
        grouped[(strategy, mode, lifetime)].append(Decimal(row["delay_from_t1_s"]))

    expected = {
        (strategy, mode, lifetime)
        for strategy in EXPECTED_STRATEGIES
        for mode in EXPECTED_MODES
        for lifetime in EXPECTED_LIFETIMES
    }
    if set(grouped) != expected or any(len(values) != 3 for values in grouped.values()):
        raise ValueError("offboarding metrics require three observed repetitions per combination")

    lines = [
        "# Generated by tests/prometheus_rules.py from results/offboarding.csv.",
        "# Do not edit measured values by hand.",
        "groups:",
        "  - name: iam_offboarding_evidence",
        "    interval: 5s",
        "    rules:",
    ]
    for strategy, mode, lifetime in sorted(grouped):
        values = grouped[(strategy, mode, lifetime)]
        mean = sum(values, Decimal(0)) / Decimal(len(values))
        lines.extend(
            [
                f"      - record: {METRIC_NAME}",
                "        labels:",
                f'          offboarding_mode: "{strategy}"',
                f'          validation_mode: "{mode}"',
                f'          lifetime_s: "{lifetime}"',
                f'          element: "{ELEMENT}"',
                f"        expr: {mean.quantize(Decimal('0.001'))}",
            ]
        )
    return "\n".join(lines) + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=REPO_ROOT / "results" / "offboarding.csv")
    parser.add_argument(
        "--output",
        type=Path,
        default=REPO_ROOT / "infra" / "prometheus" / "offboarding.rules.yml",
    )
    parser.add_argument("--check", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    validate_offboarding(args.input)
    rendered = render_rules(read_rows(args.input))
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != rendered:
            raise RuntimeError(
                f"{args.output} is stale; run .venv/bin/python -m tests.prometheus_rules"
            )
        print("Prometheus offboarding rules match canonical evidence")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    staging = staging_path(args.output)
    with staging.open("w", encoding="utf-8", newline="") as handle:
        handle.write(rendered)
        handle.flush()
        os.fsync(handle.fileno())
    staging.replace(args.output)
    print(f"generated {args.output} from {args.input}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
